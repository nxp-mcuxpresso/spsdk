"""Golden cross-check tests of the AISEC dir-v5 container against the AISEC reference.

The binaries in ``data/aisec`` were produced by the AISEC reference builder from the model
directory ``data/aisec/model`` with a fixed container salt. ``expected.json`` holds the
SHA-256 of each binary and of every member plaintext recovered by the AISEC reference
decoder. SPSDK must build the same bytes from the equivalent configuration and must
parse, verify and decrypt the reference binaries to the same plaintext.
"""

import hashlib
import json
import os
import shutil
from pathlib import Path
from typing import Any

import pytest

from spsdk.apps import nxpimage
from spsdk.image.aisec.aisec_dir import AisecDirContainer
from spsdk.image.aisec.aisec_dir_parser import (
    AisecDecodedContainer,
    AisecKeys,
    verify_container_binary,
)
from spsdk.utils.config import Config
from spsdk.utils.family import FamilyRevision
from spsdk.utils.misc import load_binary
from tests.cli_runner import CliRunner


def _golden_dir(data_dir: str) -> str:
    """Get the directory with the golden AISEC fixtures.

    :param data_dir: Test data directory.
    :return: Golden fixtures directory.
    """
    return os.path.join(data_dir, "aisec")


def _expected() -> dict[str, Any]:
    """Load the expected digests generated by the AISEC reference.

    :return: Expected digests per golden case.
    """
    path = Path(__file__).parent / "data" / "aisec" / "expected.json"
    return json.loads(path.read_text(encoding="utf-8"))


EXPECTED = _expected()
CASES = sorted(EXPECTED)


def _sha256(data: bytes) -> str:
    """Compute SHA-256 hex digest.

    :param data: Input data.
    :return: Hex digest.
    """
    return hashlib.sha256(data).hexdigest()


def _keys(golden: str, case: str) -> AisecKeys:
    """Get the key material of a golden case from its configuration.

    :param golden: Golden fixtures directory.
    :param case: Golden case name.
    :return: Key material.
    """
    config = Config.create_from_file(os.path.join(golden, f"{case}.yaml"))
    mmk = load_binary(config.get_input_file_name("keys/mmk"))
    srkh = None
    if config.get_bool("crypto/binding"):
        srkh_value = config.get_str("keys/srkh")
        srkh = (
            bytes(32)
            if srkh_value == "00" * 32
            else load_binary(config.get_input_file_name("keys/srkh"))
        )
    return AisecKeys(mmk=mmk, srkh=srkh)


def test_golden_fixture_set() -> None:
    """The golden set covers every flow, backend, KDF, binding and protection."""
    names = " ".join(CASES)
    for token in ("discrete", "integrated", "_sw_", "_optee_", "_ele_", "cmac", "hkdf"):
        assert token in names
    assert "unbound" in names and "_bind" in names
    assert len(CASES) >= 12


@pytest.mark.parametrize("family", ["mimx9352", "mimx9596"])
@pytest.mark.parametrize("case", CASES)
def test_golden_export(data_dir: str, case: str, family: str) -> None:
    """SPSDK builds the reference binary byte for byte from the equivalent configuration.

    :param data_dir: Test data directory.
    :param case: Golden case name.
    :param family: Target family; the dir-v5 wire format is family-independent.
    """
    golden = _golden_dir(data_dir)
    config = Config.create_from_file(os.path.join(golden, f"{case}.yaml"))
    config["family"] = family
    config.check(AisecDirContainer.get_validation_schemas_from_cfg(config))
    exported = AisecDirContainer.load_from_config(config).export()
    assert len(exported) == EXPECTED[case]["size"]
    assert exported == load_binary(os.path.join(golden, f"{case}.bin"))


@pytest.mark.parametrize("family", ["mimx9352", "mimx9596"])
@pytest.mark.parametrize("case", CASES)
def test_golden_parse_and_decrypt(data_dir: str, case: str, family: str) -> None:
    """SPSDK parses the reference binary and recovers the reference plaintext.

    :param data_dir: Test data directory.
    :param case: Golden case name.
    :param family: Target family; the dir-v5 wire format is family-independent.
    """
    golden = _golden_dir(data_dir)
    binary = load_binary(os.path.join(golden, f"{case}.bin"))
    assert _sha256(binary) == EXPECTED[case]["sha256"]
    keys = _keys(golden, case)

    container = AisecDirContainer.parse(
        binary, family=FamilyRevision(family), mmk=keys.mmk, srkh=keys.srkh
    )
    members = {member.name: member.get_data() for member in container.members}
    assert {name: _sha256(data) for name, data in members.items()} == EXPECTED[case]["members"]
    # The model directory is the plaintext source of every member
    for name, data in members.items():
        assert data == load_binary(os.path.join(golden, "model", name))
    # Re-export of the parsed container uses a fresh salt (no keystream reuse) ...
    assert container.container_salt is None
    assert container.export() != binary
    # ... and reproduces the reference binary only with the reference salt set explicitly
    container.container_salt = AisecDecodedContainer.decode(binary).metadata.container_salt
    assert container.export() == binary


@pytest.mark.parametrize("case", CASES)
def test_golden_verify(data_dir: str, case: str) -> None:
    """The reference binary verifies with and without keys; a wrong MMK is rejected.

    :param data_dir: Test data directory.
    :param case: Golden case name.
    """
    golden = _golden_dir(data_dir)
    binary = load_binary(os.path.join(golden, f"{case}.bin"))
    keys = _keys(golden, case)

    assert not verify_container_binary(binary).has_errors
    assert not verify_container_binary(binary, keys).has_errors
    wrong = AisecKeys(mmk=bytes(b ^ 0xFF for b in keys.mmk), srkh=keys.srkh)
    assert verify_container_binary(binary, wrong).has_errors
    if keys.srkh is not None:
        wrong_srkh = AisecKeys(mmk=keys.mmk, srkh=bytes(b ^ 0x01 for b in keys.srkh))
        assert verify_container_binary(binary, wrong_srkh).has_errors


@pytest.mark.parametrize("case", CASES)
def test_golden_tamper_rejected(data_dir: str, case: str) -> None:
    """Any flipped byte in the member area of the reference binary fails the MAC check.

    :param data_dir: Test data directory.
    :param case: Golden case name.
    """
    golden = _golden_dir(data_dir)
    binary = bytearray(load_binary(os.path.join(golden, f"{case}.bin")))
    keys = _keys(golden, case)
    for offset in (len(binary) // 2, len(binary) - 1):
        tampered = bytearray(binary)
        tampered[offset] ^= 0x01
        assert verify_container_binary(bytes(tampered), keys).has_errors


@pytest.mark.parametrize(
    "case", ["discrete_ele_hkdf_bind_mixed", "integrated_ele_cmac_bind", "discrete_ele_cmac_bind"]
)
def test_golden_cli(cli_runner: CliRunner, tmp_path: Path, data_dir: str, case: str) -> None:
    """The nxpimage CLI exports, verifies and parses the golden cases.

    :param cli_runner: CLI runner.
    :param tmp_path: Temporary directory.
    :param data_dir: Test data directory.
    :param case: Golden case name.
    """
    work = tmp_path / "golden"
    shutil.copytree(_golden_dir(data_dir), work)
    reference = work / f"{case}.bin"

    cli_runner.invoke(nxpimage.main, ["aisec", "export", "-c", str(work / f"{case}.yaml")])
    assert load_binary(str(work / "output" / f"{case}.bin")) == load_binary(str(reference))

    args = ["-b", str(reference), "-k", str(work / "keys" / "mmk_aes256.bin")]
    args += ["--srkh", str(work / "keys" / "srkh.bin")]
    cli_runner.invoke(nxpimage.main, ["aisec", "verify", *args])

    parsed = tmp_path / "parsed"
    cli_runner.invoke(nxpimage.main, ["aisec", "parse", "-f", "mimx9596", *args, "-o", str(parsed)])
    shutil.copy(work / "keys" / "mmk_aes256.bin", parsed / "mmk.bin")
    config = Config.create_from_file(str(parsed / "aisec_config.yaml"))
    rebuilt = AisecDirContainer.load_from_config(config)
    # A rebuild uses a fresh salt; the decoded content must still match the reference
    keys = AisecKeys(mmk=load_binary(str(parsed / "mmk.bin")), srkh=rebuilt.srkh)
    assert not verify_container_binary(rebuilt.export(), keys).has_errors
    assert {member.name: _sha256(member.get_data()) for member in rebuilt.members} == EXPECTED[
        case
    ]["members"]
